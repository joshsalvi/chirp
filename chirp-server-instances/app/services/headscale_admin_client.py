"""
Queries the bundled self-hosted Headscale server's own node list — a
genuinely different concern from tailscale_manager.py, which is this
server acting as a Tailscale CLIENT of some coordination server
(bundled Headscale, or a real Tailscale.com account). This module is
the other side: chirp-server-instances asking the bundled Headscale
SERVER "who's actually connected to this tailnet right now" — only
meaningful when self-hosting the bundled Headscale, since a real
Tailscale.com account's own admin console already shows this and
there's no reason to duplicate it here.

Reachability: NOT headscale's own gRPC API directly — confirmed
directly, the hard way (a real "illegal request line" error), that its
gRPC listener only speaks raw gRPC (HTTP/2 + protobuf framing), not a
REST/JSON gateway the way some other Go services bundle on the same
port; headscale's own docs describe that port as being for CLI remote
control specifically, and it doesn't ship a grpc-gateway translation
layer. Standing up a real Python gRPC client (generated protobuf
stubs matching headscale's exact .proto schema) for one read-only
endpoint wasn't worth the dependency. Instead: a small stdlib-only
HTTP wrapper (headscale/api-wrapper.py) runs as a second process
inside the headscale container itself, shells out to `headscale nodes
list` (the officially supported CLI, guaranteed-correct output), and
serves the result on 127.0.0.1:50444 — published by docker-compose.yml
to the HOST's own loopback only (127.0.0.1:50444:50444, never 0.0.0.0),
reachable from chirp-server-instances (network_mode: host puts it on
the host's own network namespace) but never from the LAN or internet.

Auth: a shared secret, auto-generated by headscale/entrypoint.sh the
same zero-manual-steps way the tailscale preauth key already is,
written to the same shared volume at /shared/apikey — the wrapper
checks this as a Bearer token before running anything.

Field-name caveat: headscale CLI's own JSON output schema wasn't
verifiable against a live instance before shipping — this parses
defensively, checking multiple plausible key-name variants
(camelCase, snake_case, and the shortened "ips" some downstream
tooling documents) rather than assuming one. Verify the actual
response shape against a real running instance and adjust here if a
field genuinely isn't showing up.
"""
import logging
from datetime import datetime, timezone
from typing import Optional

import httpx

logger = logging.getLogger("chirp.headscale_admin")

HEADSCALE_API_BASE = "http://127.0.0.1:50444"
API_KEY_FILE = "/shared/apikey"


def _read_api_key() -> Optional[str]:
    try:
        with open(API_KEY_FILE) as f:
            key = f.read().strip()
        return key or None
    except FileNotFoundError:
        return None
    except Exception as e:
        logger.warning("Could not read Headscale API key from %s: %s", API_KEY_FILE, e)
        return None


def _get(field, *names, default=None):
    """Check a dict for the first of several possible key-name variants."""
    for name in names:
        if name in field:
            return field[name]
    return default


def get_nodes() -> dict:
    """
    Returns {"available": bool, "nodes": [...], "error": str|None}.
    available=False means either the API key isn't provisioned yet (the
    bundled Headscale hasn't finished its own startup bootstrap — same
    timing this whole feature already handles for the tailscale key) or
    this isn't using the bundled Headscale at all. Never raises — a
    Global Admin panel calling this should show "unavailable", not 500.
    """
    api_key = _read_api_key()
    if not api_key:
        return {"available": False, "nodes": [], "error": None}

    try:
        resp = httpx.get(
            f"{HEADSCALE_API_BASE}/nodes",
            headers={"Authorization": f"Bearer {api_key}"},
            timeout=20.0,   # the wrapper's CLI call can take up to 15 s before it gives up
        )
        if resp.status_code >= 400:
            try:
                msg = resp.json().get("error") or resp.text
            except Exception:
                msg = resp.text
            raise RuntimeError(msg or f"HTTP {resp.status_code}")
        data = resp.json()
    except Exception as e:
        logger.warning("Headscale node list request failed: %s", e)
        return {"available": True, "nodes": [], "error": str(e)}

    raw_nodes = _get(data, "nodes", "node", default=[]) or [] if isinstance(data, dict) else []
    nodes = []
    now = datetime.now(timezone.utc)
    for n in raw_nodes:
        # This function's own docstring promises "never raises" — but
        # this loop is exactly where that promise could be broken: the
        # real Headscale CLI's JSON shape for `nodes list --output
        # json` couldn't be verified against a live instance before
        # shipping (see this module's own docstring), so a genuinely
        # different structure here must degrade to skipping that one
        # node, not a 500 for the whole panel. Reported directly, with
        # a real 500 from this exact gap.
        try:
            if not isinstance(n, dict):
                logger.warning("Skipping a Headscale node entry that wasn't a dict: %r", n)
                continue
            last_seen_raw = _get(n, "lastSeen", "last_seen")
            last_seen_iso = None
            if last_seen_raw:
                try:
                    # Go's standard JSON time marshaling is RFC3339 — "Z"
                    # isn't accepted by fromisoformat on Python <3.11, normalize it.
                    last_seen_iso = datetime.fromisoformat(
                        str(last_seen_raw).replace("Z", "+00:00")
                    ).isoformat()
                except Exception:
                    last_seen_iso = last_seen_raw  # pass through raw string rather than drop it

            user_field = _get(n, "user")
            nodes.append({
                "id": _get(n, "id"),
                "name": _get(n, "name", "givenName", "given_name"),
                "hostname": _get(n, "hostname"),
                "ip_addresses": _get(n, "ipAddresses", "ip_addresses", "ips", default=[]) or [],
                "online": bool(_get(n, "online", default=False)),
                "last_seen": last_seen_iso,
                "expiry": _get(n, "expiry"),
                "user": user_field.get("name") if isinstance(user_field, dict) else (user_field if isinstance(user_field, str) else None),
            })
        except Exception as e:
            logger.warning("Skipping a Headscale node entry that didn't parse as expected: %s", e)
            continue

    # Online first, then most-recently-seen — the people actually
    # checking this panel care most about who's up right now.
    try:
        nodes.sort(key=lambda n: (not n["online"], n["last_seen"] or ""), reverse=False)
    except Exception:
        pass  # unsorted is still usable; a 500 here would defeat the whole point of this function never raising
    return {"available": True, "nodes": nodes, "error": None}
