#!/usr/bin/env bash
#
# Generates a new, fully independent chirp-server instance — one command
# per tenant/location, instead of hand-writing a new docker-compose file
# each time. Ported from the same proven pattern as the original
# docker-compose.instance-a/b/c.yml files (which stay in the repo as
# real, working examples of the output this script produces), just
# parameterized instead of three fixed names.
#
# Usage:
#   ./scripts/new-instance.sh <name> <port>
#
# Example:
#   ./scripts/new-instance.sh natick 8768
#   docker compose -f docker-compose.instance-natick.yml up -d
#
# <name> becomes part of the container name, the data directory, and the
# env var prefix for that instance's own secrets — keep it short,
# lowercase, and shell/Docker-safe (letters, numbers, hyphens only).
# <port> must be a real, currently-unused port on this host — nothing
# here checks that for you; network_mode: host means a collision fails
# at container start, the same way the original Caddy port conflict did
# earlier in this project, not at generation time.
set -euo pipefail

if [ $# -ne 2 ]; then
  echo "Usage: $0 <name> <port>" >&2
  echo "Example: $0 natick 8768" >&2
  exit 1
fi

NAME="$1"
PORT="$2"

if ! [[ "$NAME" =~ ^[a-z0-9][a-z0-9-]*$ ]]; then
  echo "Error: name must be lowercase letters, numbers, and hyphens only (got: $NAME)" >&2
  exit 1
fi
if ! [[ "$PORT" =~ ^[0-9]+$ ]] || [ "$PORT" -lt 1 ] || [ "$PORT" -gt 65535 ]; then
  echo "Error: port must be a real port number 1-65535 (got: $PORT)" >&2
  exit 1
fi

OUT_FILE="docker-compose.instance-${NAME}.yml"
if [ -f "$OUT_FILE" ]; then
  echo "Error: $OUT_FILE already exists — pick a different name, or delete it first if you genuinely want to regenerate it." >&2
  exit 1
fi

# Env var prefix: NAME uppercased, hyphens to underscores (shell env var
# names can't contain hyphens) — e.g. "natick" -> "NATICK",
# "back-yard" -> "BACK_YARD".
ENV_PREFIX=$(echo "$NAME" | tr 'a-z-' 'A-Z_')

cat > "$OUT_FILE" <<EOF
# Chirp Server — instance "${NAME}"
#
# Generated by scripts/new-instance.sh — a fully independent
# chirp-server, the real, complete, already-tested application, not a
# reimplementation of it. Its own container, its own port (${PORT}),
# its own data directory, its own database — genuinely isolated from
# every other instance because it's a separate process with separate
# storage, not a shared-database tenant model.
#
# Run this instance on its own:
#   docker compose -f ${OUT_FILE} up -d
#
# Access: http://localhost:${PORT} (or http://<host-ip>:${PORT} from
# another device on the LAN — network_mode: host is kept here so this
# instance retains real LAN device auto-discovery for pairing actual
# hardware, not just API behavior in isolation).
#
# AI/eBird keys: set once in this instance's own Settings page after
# first boot (Settings → AI Provider / eBird). See
# scripts/copy-instance-settings.py to copy those specific keys from an
# already-configured instance into this one, instead of re-entering
# them by hand.

name: chirp-instance-${NAME}

services:
  chirp-server-${NAME}:
    build:
      context: .
      dockerfile: Dockerfile
    container_name: chirp-server-${NAME}
    restart: unless-stopped
    network_mode: host
    labels:
      - "net.unraid.docker.webui=http://[IP]:[PORT:${PORT}]/"
      - "net.unraid.docker.shell=bash"
      - "net.unraid.docker.name=Chirp (${NAME})"
      - "com.centurylinklabs.watchtower.enable=false"
    volumes:
      - \${CHIRP_${ENV_PREFIX}_DATA_DIR:-/mnt/user/data/media/miscellaneous/chirp-data-${NAME}}:/app/data
    environment:
      - CHIRP_SECRET_KEY=\${CHIRP_${ENV_PREFIX}_SECRET_KEY:-changeme-${NAME}-use-a-real-secret}
      - CHIRP_DEVICE_API_KEY=\${CHIRP_${ENV_PREFIX}_DEVICE_API_KEY:-chirp-device-key-${NAME}-change-me}
      - CHIRP_EBIRD_API_KEY=\${CHIRP_EBIRD_API_KEY:-}
      - CHIRP_DATA_DIR=/app/data
      - CHIRP_RECORDINGS_DIR=/app/data/recordings
      - CHIRP_MEDIA_DIR=/app/data/media/birds
      - CHIRP_DB_URL=sqlite:////app/data/chirp.db
      - CHIRP_HOST=0.0.0.0
      - CHIRP_PORT=${PORT}
      - CHIRP_SERVER_URL=\${CHIRP_${ENV_PREFIX}_SERVER_URL:-}
      - TZ=\${TZ:-America/New_York}
    healthcheck:
      test: ["CMD", "curl", "-f", "http://localhost:${PORT}/api/v1/health"]
      interval: 30s
      timeout: 10s
      retries: 3
      start_period: 45s

  chirp-server-${NAME}-cloudflared:
    image: cloudflare/cloudflared:latest
    container_name: chirp-server-${NAME}-cloudflared
    restart: unless-stopped
    network_mode: host
    command: tunnel --no-autoupdate run --token \${CHIRP_${ENV_PREFIX}_CLOUDFLARE_TUNNEL_TOKEN:-}
    labels:
      - "net.unraid.docker.name=Chirp (${NAME}) Cloudflare Tunnel"
      - "com.centurylinklabs.watchtower.enable=false"
EOF

echo "Created $OUT_FILE"

# Register this instance in launcher/instances.json — what the launcher
# (chirp-launcher, see docker-compose.yml) reads to build its list of
# instances. Lives inside launcher/ itself (not a separate top-level
# file) since a real, confirmed OCI runtime bug meant mounting it as
# its own separate, nested bind mount inside the already-read-only
# launcher/ directory mount failed to even start the container, on any
# machine — see docker-compose.yml's own comment on this. Uses python3
# for this rather than bash/sed JSON editing, since malformed JSON here
# would break the launcher page for every instance, not just this new
# one — worth getting right reliably rather than cheaply.
python3 - "$NAME" "$PORT" <<'PYEOF'
import json
import sys

name, port = sys.argv[1], int(sys.argv[2])
path = "launcher/instances.json"

try:
    with open(path) as f:
        instances = json.load(f)
except FileNotFoundError:
    instances = []

if any(inst.get("name") == name for inst in instances):
    print(f"Warning: launcher/instances.json already has an entry named '{name}' — not adding a duplicate.")
else:
    instances.append({
        "name": name,
        "display_name": f"Chirp ({name})",
        "port": port,
        "public_url": None,
    })
    with open(path, "w") as f:
        json.dump(instances, f, indent=2)
        f.write("\n")
    print(f"Registered '{name}' in launcher/instances.json — it'll now show up on the launcher page (chirp-launcher, port 8760).")
PYEOF

echo ""
echo "Next steps:"
echo "  1. docker compose -f $OUT_FILE up -d"
echo "  2. Open http://<this-host-ip>:${PORT} and complete first-run setup"
echo "  3. For HTTPS: create a Cloudflare Tunnel for this instance (see docs/CLOUDFLARE_TUNNEL.md),"
echo "     set CHIRP_${ENV_PREFIX}_CLOUDFLARE_TUNNEL_TOKEN in your .env file"
echo "  4. If this instance has its own public Cloudflare Tunnel URL, add it to this instance's"
echo "     \"public_url\" field in launcher/instances.json so the launcher links there instead of a LAN port"
echo "  5. To reuse an already-configured instance's AI/eBird keys instead of re-entering them:"
echo "     python3 scripts/copy-instance-settings.py <source-data-dir> /mnt/user/data/media/miscellaneous/chirp-data-${NAME}"
